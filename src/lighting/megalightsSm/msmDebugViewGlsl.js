import { toGlslFloatLiteral } from "./msmNormalFromDepthGlsl.js";
import {
	MSM_SCREEN_COMPOSITE_MINIMUM_BASE_LUMINANCE,
	MSM_SCREEN_COMPOSITE_MINIMUM_UNSHADOWED_LUMINANCE,
	MSM_SCREEN_COMPOSITE_NEUTRAL_FACTOR,
} from "./msmScreenCompositeCore.js";
import { MSM_VIEW_OPTIONS } from "./msmViewportSettingsCore.js";


export const MSM_DEBUG_VIEW_UNIFORMS = Object.freeze([
	Object.freeze({
		name: "uMsmCompositeDebugMode",
		glslType: "float",
		meaning: "index of MegaLightsSMView: 0 Composite, 1 ShadowFactor, 2 LightCoverage",
	}),
]);


export const MSM_DEBUG_VIEW_FUNCTIONS = Object.freeze([
	"msmDebugViewShadowFactor",
	"msmDebugViewLightCoverage",
	"msmApplyDebugView",
]);


const DEBUG_VIEW_GLSL_CONSTANTS = Object.freeze([
	Object.freeze({ glslName: "MSM_VIEW_COMPOSITE", value: MSM_VIEW_OPTIONS.indexOf("Composite") }),
	Object.freeze({ glslName: "MSM_VIEW_SHADOW_FACTOR", value: MSM_VIEW_OPTIONS.indexOf("ShadowFactor") }),
	Object.freeze({
		glslName: "MSM_VIEW_MINIMUM_ENERGY",
		value: MSM_SCREEN_COMPOSITE_MINIMUM_UNSHADOWED_LUMINANCE,
	}),
	Object.freeze({
		glslName: "MSM_VIEW_MINIMUM_BASE_LUMINANCE",
		value: MSM_SCREEN_COMPOSITE_MINIMUM_BASE_LUMINANCE,
	}),
	Object.freeze({
		glslName: "MSM_VIEW_NEUTRAL_FACTOR",
		value: MSM_SCREEN_COMPOSITE_NEUTRAL_FACTOR,
	}),
]);


export function buildDebugViewUniformDeclarations() {
	return MSM_DEBUG_VIEW_UNIFORMS.map(
		(uniform) => "uniform " + uniform.glslType + " " + uniform.name + ";",
	).join("\n");
}

function buildConstantDeclarations() {
	return DEBUG_VIEW_GLSL_CONSTANTS.map(
		(constant) => "const float " + constant.glslName + " = " + toGlslFloatLiteral(constant.value) + ";",
	).join("\n");
}


export function buildDebugViewGlsl() {
	return [
		"// MSM inspection views of MegaLightsSMView. Generated by",
		"// src/lighting/megalightsSm/msmDebugViewGlsl.js - do not edit by hand.",
		buildConstantDeclarations(),
		"",
		"// ShadowFactor: the ONE scalar of mode A, painted as grey. White means the",
		"// pixel was not touched; the darker it is, the more local light was removed.",
		"vec3 msmDebugViewShadowFactor(const in vec2 irradiancePair) {",
		"\treturn vec3(msmScreenCompositeFactorOf(irradiancePair));",
		"}",
		"",
		"// LightCoverage: the fraction of the light of this pixel that the MSM owns,",
		"// using the SAME importance correction as the composite, so the two views",
		"// tell one story. Black means no eligible local light reaches this pixel and",
		"// mode A can NEVER change it. Grey to white means the local lamps dominate.",
		"// The warm tint marks where the shadow is actually cutting that light.",
		"vec3 msmDebugViewLightCoverage(const in vec2 irradiancePair) {",
		"\tfloat weightSum = max(irradiancePair.y, 0.0);",
		"\tfloat baseLuminance = max(uMsmCompositeBaseLuminance, MSM_VIEW_MINIMUM_BASE_LUMINANCE);",
		"\tfloat coverage = weightSum / (weightSum + baseLuminance);",
		"\tfloat hasEnergy = step(MSM_VIEW_MINIMUM_ENERGY, weightSum);",
		"\tfloat occlusion = clamp(MSM_VIEW_NEUTRAL_FACTOR - msmScreenCompositeVisibility(irradiancePair), 0.0, 1.0);",
		"\tvec3 unoccluded = vec3(coverage);",
		"\tvec3 occluded = vec3(coverage, coverage * 0.35, coverage * 0.10);",
		"\treturn mix(vec3(0.0), mix(unoccluded, occluded, occlusion), hasEnergy);",
		"}",
		"",
		"// UNIFORM branch: with Composite selected this returns the shipped colour",
		"// before the extra fetch, so inspecting costs nothing when nobody inspects.",
		"vec3 msmApplyDebugView(const in vec3 compositedColor, const in vec2 screenUv, const in float requestedView) {",
		"\tif (MSM_VIEW_COMPOSITE >= requestedView) return compositedColor;",
		"\tvec2 irradiancePair = texture2D(tMsmIrradiance, msmScreenCompositeReducedUv(screenUv)).rg;",
		"\tif (MSM_VIEW_SHADOW_FACTOR >= requestedView) return msmDebugViewShadowFactor(irradiancePair);",
		"\treturn msmDebugViewLightCoverage(irradiancePair);",
		"}",
	].join("\n");
}
