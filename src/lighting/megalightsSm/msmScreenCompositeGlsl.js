import { toGlslFloatLiteral } from "./msmNormalFromDepthGlsl.js";
import {
  MSM_SCREEN_COMPOSITE_FETCHES_PER_PIXEL,
  MSM_SCREEN_COMPOSITE_MINIMUM_BASE_LUMINANCE,
  MSM_SCREEN_COMPOSITE_MINIMUM_UNSHADOWED_LUMINANCE,
  MSM_SCREEN_COMPOSITE_NEUTRAL_FACTOR,
} from "./msmScreenCompositeCore.js";


export const MSM_SCREEN_COMPOSITE_UNIFORMS = Object.freeze([
  Object.freeze({
    name: "tMsmIrradiance",
    glslType: "sampler2D",
    meaning: "reduced resolution irradiance buffer written by MSM-F21: r is shadowed, g is unshadowed",
  }),
  Object.freeze({
    name: "uMsmCompositeTexel",
    glslType: "vec2",
    meaning: "1 over the size of that buffer, used to fetch the centre of its texel",
  }),
  Object.freeze({
    name: "uMsmCompositeStrength",
    glslType: "float",
    meaning: "maximum fraction of local light the shadow may remove, in [0, 1]",
  }),
  Object.freeze({
    name: "uMsmCompositeBaseLuminance",
    glslType: "float",
    meaning: "sun plus ambient of the pixel: the base of the importance correction",
  }),
  Object.freeze({
    name: "uMsmCompositeOn",
    glslType: "float",
    meaning: "1 composites, 0 returns the colour untouched with the SAME program (gate G9)",
  }),
]);


export const MSM_SCREEN_COMPOSITE_SAMPLER_COUNT = 1;
export const MSM_SCREEN_COMPOSITE_TEXTURE_FETCH_COUNT = MSM_SCREEN_COMPOSITE_FETCHES_PER_PIXEL;


export const MSM_SCREEN_COMPOSITE_REQUIRED_FUNCTIONS = Object.freeze([
  "msmScreenCompositeReducedUv",
  "msmScreenCompositeVisibility",
  "msmScreenCompositeFactorOf",
  "msmScreenComposite",
]);


export const MSM_SCREEN_COMPOSITE_GLSL_CONSTANTS = Object.freeze([
  Object.freeze({
    glslName: "MSM_COMPOSITE_MINIMUM_UNSHADOWED_LUMINANCE",
    value: MSM_SCREEN_COMPOSITE_MINIMUM_UNSHADOWED_LUMINANCE,
  }),
  Object.freeze({
    glslName: "MSM_COMPOSITE_MINIMUM_BASE_LUMINANCE",
    value: MSM_SCREEN_COMPOSITE_MINIMUM_BASE_LUMINANCE,
  }),
  Object.freeze({
    glslName: "MSM_COMPOSITE_NEUTRAL_FACTOR",
    value: MSM_SCREEN_COMPOSITE_NEUTRAL_FACTOR,
  }),
]);


export function buildScreenCompositeUniformDeclarations() {
  return MSM_SCREEN_COMPOSITE_UNIFORMS.map(
    (uniform) => "uniform " + uniform.glslType + " " + uniform.name + ";",
  ).join("\n");
}

function buildConstantDeclarations() {
  return MSM_SCREEN_COMPOSITE_GLSL_CONSTANTS.map(
    (constant) => "const float " + constant.glslName + " = " + toGlslFloatLiteral(constant.value) + ";",
  ).join("\n");
}









export function buildScreenCompositeGlsl() {
  return [
    "// MSM-F22 mode A: multiplicative composite on screen. Generated by",
    "// src/lighting/megalightsSm/msmScreenCompositeGlsl.js - do not edit by hand.",
    buildConstantDeclarations(),
    "",
    "// Centre of the texel of the reduced buffer: nearest fetch, no filtering.",
    "// The depth aware upsample belongs to MSM-F23, not here.",
    "vec2 msmScreenCompositeReducedUv(const in vec2 screenUv) {",
    "\treturn (floor(screenUv / uMsmCompositeTexel) + vec2(0.5)) * uMsmCompositeTexel;",
    "}",
    "",
    "// Fraction of the estimated local light of the pixel that survived the shadow.",
    "// A pixel with no energy answers the neutral factor instead of black.",
    "float msmScreenCompositeVisibility(const in vec2 irradiancePair) {",
    "\tfloat unshadowedLuminance = irradiancePair.y;",
    "\tfloat hasEnergy = step(MSM_COMPOSITE_MINIMUM_UNSHADOWED_LUMINANCE, unshadowedLuminance);",
    "\tfloat safeUnshadowedLuminance = max(unshadowedLuminance, MSM_COMPOSITE_MINIMUM_UNSHADOWED_LUMINANCE);",
    "\tfloat measuredVisibility = clamp(irradiancePair.x / safeUnshadowedLuminance, 0.0, 1.0);",
    "\treturn mix(MSM_COMPOSITE_NEUTRAL_FACTOR, measuredVisibility, hasEnergy);",
    "}",
    "",
    "// The ONE scalar of mode A, in [0, 1]. Twin of msmScreenCompositeFactor in JS.",
    "float msmScreenCompositeFactorOf(const in vec2 irradiancePair) {",
    "\tfloat occlusion = MSM_COMPOSITE_NEUTRAL_FACTOR - msmScreenCompositeVisibility(irradiancePair);",
    "\tfloat weightSum = max(irradiancePair.y, 0.0);",
    "\tfloat baseLuminance = max(uMsmCompositeBaseLuminance, MSM_COMPOSITE_MINIMUM_BASE_LUMINANCE);",
    "\tfloat shadowStrength = clamp(occlusion * uMsmCompositeStrength, 0.0, 1.0);",
    "\tfloat importanceCorrection = weightSum / (weightSum + baseLuminance);",
    "\treturn clamp(MSM_COMPOSITE_NEUTRAL_FACTOR - shadowStrength * importanceCorrection, 0.0, 1.0);",
    "}",
    "",
    "// One fetch per pixel, always. uMsmCompositeOn = 0 returns the colour",
    "// untouched WITHOUT changing the program (same shader, same texture units).",
    "vec3 msmScreenComposite(const in vec3 litColor, const in vec2 screenUv) {",
    "\tvec2 irradiancePair = texture2D(tMsmIrradiance, msmScreenCompositeReducedUv(screenUv)).rg;",
    "\tfloat compositeFactor = msmScreenCompositeFactorOf(irradiancePair);",
    "\treturn mix(litColor, litColor * compositeFactor, uMsmCompositeOn);",
    "}",
  ].join("\n");
}
