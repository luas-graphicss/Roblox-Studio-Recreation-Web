export const VSM_GLSL_UNIFORM_NAMES = Object.freeze([
  "uMglShadowAtlas",
  "uMglShadowAtlasSize",
  "uMglVirtualShadowMapLightLimit",
]);

export const VSM_GLSL_FUNCTION_NAMES = Object.freeze([
  "mglUnpackPageDepth",
  "mglLightMayOwnShadowPage",
  "mglProjectIntoShadowPage",
  "mglReceiverPlaneTangents",
  "mglPageStepAlongWorldDirection",
  "mglReceiverPlaneDepthSlope",
  "mglTapReferenceDepth",
  "mglSampleVirtualShadowMapVisibility",
  "mglVirtualShadowMapTraceState",
]);

export const SHADOW_KERNEL_FORBIDDEN_TOKENS = Object.freeze(["dFdx", "dFdy", "fwidth"]);


export const VSM_GLSL_STATE_CONSTANTS = Object.freeze({
  visible: "MGL_VSM_STATE_VISIBLE",
  occluded: "MGL_VSM_STATE_OCCLUDED",
  unknown: "MGL_VSM_STATE_UNKNOWN",
});


export function buildVirtualShadowMapGlsl() {
  return [
    "// ---- ML-F15: virtual shadow map sampling (generated by mlVsmSampleGlsl.js) ----",
    "uniform sampler2D uMglShadowAtlas;   // the ENGINE atlas pages, never a second atlas",
    "uniform vec2 uMglShadowAtlasSize;    // atlas size in texels",
    "uniform int uMglVirtualShadowMapLightLimit; // how many lights may own pages in this tier",
    "",
    "const float " + VSM_GLSL_STATE_CONSTANTS.visible + " = 0.0;",
    "const float " + VSM_GLSL_STATE_CONSTANTS.occluded + " = 1.0;",
    "const float " + VSM_GLSL_STATE_CONSTANTS.unknown + " = 2.0;",
    "",
    "// Same constants as three.js unpackRGBAToDepth and as the CPU mirror in",
    "// mlVsmSampleCore.js. If these three numbers ever disagree, the shader and",
    "// the proof disagree by a bias nobody can find.",
    "const float MGL_VSM_UNPACK_DOWNSCALE = 255.0 / 256.0;",
    "const vec4 MGL_VSM_UNPACK_FACTORS = vec4(",
    "  MGL_VSM_UNPACK_DOWNSCALE / 16777216.0,",
    "  MGL_VSM_UNPACK_DOWNSCALE / 65536.0,",
    "  MGL_VSM_UNPACK_DOWNSCALE / 256.0,",
    "  MGL_VSM_UNPACK_DOWNSCALE);",
    "",
    "float mglUnpackPageDepth(const in vec4 packedDepth) {",
    "  return dot(packedDepth, MGL_VSM_UNPACK_FACTORS);",
    "}",
    "",
    "bool mglLightMayOwnShadowPage(const in int lightIndex) {",
    "  return lightIndex >= 0 && lightIndex < uMglVirtualShadowMapLightLimit;",
    "}",
    "",
    "// pageScaleOffset = (su, sv, ou, ov) of the slot; su <= 0.0 means NO page.",
    "bool mglProjectIntoShadowPage(",
    "  const in mat4 lightViewProjection,",
    "  const in vec4 pageScaleOffset,",
    "  const in vec3 worldPosition,",
    "  out vec3 pageCoordinate",
    ") {",
    "  pageCoordinate = vec3(0.0);",
    "  if (pageScaleOffset.x <= 0.0) return false;",
    "  vec4 clipPosition = lightViewProjection * vec4(worldPosition, 1.0);",
    "  if (clipPosition.w <= 0.0) return false;",
    "  vec3 normalizedDevice = clipPosition.xyz / clipPosition.w;",
    "  if (abs(normalizedDevice.x) >= 1.0 || abs(normalizedDevice.y) >= 1.0) return false;",
    "  if (normalizedDevice.z >= 1.0 || normalizedDevice.z <= -1.0) return false;",
    "  pageCoordinate = vec3(",
    "    (normalizedDevice.xy * 0.5 + 0.5) * pageScaleOffset.xy + pageScaleOffset.zw,",
    "    normalizedDevice.z * 0.5 + 0.5);",
    "  return true;",
    "}",
    "",
    "// ---- contact preserving bias: mirror of mlVsmContactBiasCore.js ----",
    "// The page packs depth in RGBA8, so one part in 2^24 is the smallest step it",
    "// can hold, and two steps cover the rounding of what was stored and of what",
    "// is read back. Once the compare follows the receiver plane, that is ALL the",
    "// slack it needs: a constant bias is what used to leave a lit band, and that",
    "// band is the gap between an object and its shadow.",
    "const float MGL_VSM_CONTACT_DEPTH_SLACK = 2.0 / 16777216.0;",
    "// Page axes closer to parallel than this sine mean a receiver seen edge on by",
    "// the light: the slope would divide by almost nothing, so the page bias stays.",
    "const float MGL_VSM_MIN_PAGE_AXIS_SINE = 1e-4;",
    "",
    "// Two unit tangents of the receiver plane. The helper axis is the world axis",
    "// LEAST aligned with the normal, so the cross product never collapses.",
    "void mglReceiverPlaneTangents(",
    "  const in vec3 receiverWorldNormal,",
    "  out vec3 firstTangent,",
    "  out vec3 secondTangent",
    ") {",
    "  vec3 planeNormal = normalize(receiverWorldNormal);",
    "  vec3 absoluteNormal = abs(planeNormal);",
    "  vec3 helperAxis = vec3(0.0, 0.0, 1.0);",
    "  if (absoluteNormal.x <= absoluteNormal.y && absoluteNormal.x <= absoluteNormal.z) {",
    "    helperAxis = vec3(1.0, 0.0, 0.0);",
    "  } else if (absoluteNormal.y <= absoluteNormal.z) {",
    "    helperAxis = vec3(0.0, 1.0, 0.0);",
    "  }",
    "  firstTangent = normalize(cross(planeNormal, helperAxis));",
    "  secondTangent = cross(planeNormal, firstTangent);",
    "}",
    "",
    "// Exact page travel along a world direction. In homogeneous clip space the",
    "// walk along the plane is clip(s) = centerClip + s * directionClip, so",
    "//   d(ndc)/ds = (directionClip.xyz - centerNdc * directionClip.w) / centerClip.w",
    "// Analytic and continuous, silhouette included: this is why the slope needs",
    "// no screen derivative.",
    "vec3 mglPageStepAlongWorldDirection(",
    "  const in mat4 lightViewProjection,",
    "  const in vec4 pageScaleOffset,",
    "  const in float centerClipW,",
    "  const in vec3 centerNdc,",
    "  const in vec3 worldDirection",
    ") {",
    "  vec4 directionClip = lightViewProjection * vec4(worldDirection, 0.0);",
    "  vec3 ndcStep = (directionClip.xyz - centerNdc * directionClip.w) / centerClipW;",
    "  return vec3(",
    "    0.5 * pageScaleOffset.x * ndcStep.x,",
    "    0.5 * pageScaleOffset.y * ndcStep.y,",
    "    0.5 * ndcStep.z);",
    "}",
    "",
    "// dDepth/du and dDepth/dv of the receiver plane, in page units. false means",
    "// there is no usable plane - no page, no normal, point behind the light, or a",
    "// receiver seen edge on - and the caller keeps the legacy page bias.",
    "bool mglReceiverPlaneDepthSlope(",
    "  const in mat4 lightViewProjection,",
    "  const in vec4 pageScaleOffset,",
    "  const in vec3 worldPosition,",
    "  const in vec3 receiverWorldNormal,",
    "  out vec2 depthSlope",
    ") {",
    "  depthSlope = vec2(0.0);",
    "  if (pageScaleOffset.x <= 0.0) return false;",
    "  if (dot(receiverWorldNormal, receiverWorldNormal) <= 0.0) return false;",
    "  vec4 centerClip = lightViewProjection * vec4(worldPosition, 1.0);",
    "  if (centerClip.w <= 0.0) return false;",
    "  vec3 centerNdc = centerClip.xyz / centerClip.w;",
    "  vec3 firstTangent;",
    "  vec3 secondTangent;",
    "  mglReceiverPlaneTangents(receiverWorldNormal, firstTangent, secondTangent);",
    "  vec3 firstStep = mglPageStepAlongWorldDirection(",
    "    lightViewProjection, pageScaleOffset, centerClip.w, centerNdc, firstTangent);",
    "  vec3 secondStep = mglPageStepAlongWorldDirection(",
    "    lightViewProjection, pageScaleOffset, centerClip.w, centerNdc, secondTangent);",
    "  float pageAxisDeterminant = firstStep.x * secondStep.y - secondStep.x * firstStep.y;",
    "  float pageAxisScale = length(firstStep.xy) * length(secondStep.xy);",
    "  if (pageAxisScale <= 0.0) return false;",
    "  if (abs(pageAxisDeterminant) < MGL_VSM_MIN_PAGE_AXIS_SINE * pageAxisScale) return false;",
    "  depthSlope = vec2(",
    "    (firstStep.z * secondStep.y - secondStep.z * firstStep.y) / pageAxisDeterminant,",
    "    (firstStep.x * secondStep.z - secondStep.x * firstStep.z) / pageAxisDeterminant);",
    "  return true;",
    "}",
    "",
    "// The depth ONE tap compares against. With a receiver plane the reference is",
    "// the depth the receiver ITSELF has at that tap, so the contact point keeps",
    "// its own depth and the shadow touches the object: ZERO GAP. tapUv is the",
    "// CLAMPED tap, so a tap held at the page border compares against the border.",
    "float mglTapReferenceDepth(",
    "  const in vec3 pageCoordinate,",
    "  const in vec2 tapUv,",
    "  const in vec2 depthSlope,",
    "  const in bool hasReceiverPlane,",
    "  const in float pageDepthBias",
    ") {",
    "  if (!hasReceiverPlane) return pageCoordinate.z - pageDepthBias;",
    "  float planeDepth = pageCoordinate.z + dot(depthSlope, tapUv - pageCoordinate.xy);",
    "  return clamp(planeDepth - MGL_VSM_CONTACT_DEPTH_SLACK, 0.0, 1.0);",
    "}",
    "",
    "// 4 taps, every one clamped inside pageBounds = (minU, minV, maxU, maxV):",
    "// the neighbouring page must never bleed into this filter. Every tap compares",
    "// against the depth of the receiver plane AT THAT TAP, so the shadow starts",
    "// exactly where the object touches the receiver.",
    "float mglSampleVirtualShadowMapVisibility(",
    "  const in mat4 lightViewProjection,",
    "  const in vec4 pageScaleOffset,",
    "  const in vec4 pageBounds,",
    "  const in vec3 worldPosition,",
    "  const in float depthBias,",
    "  const in vec3 receiverWorldNormal",
    ") {",
    "  vec3 pageCoordinate;",
    "  if (!mglProjectIntoShadowPage(lightViewProjection, pageScaleOffset, worldPosition, pageCoordinate)) {",
    "    return 1.0;",
    "  }",
    "  vec2 texelStep = 1.0 / uMglShadowAtlasSize;",
    "  vec2 depthSlope;",
    "  bool hasReceiverPlane = mglReceiverPlaneDepthSlope(",
    "    lightViewProjection, pageScaleOffset, worldPosition, receiverWorldNormal, depthSlope);",
    "  float visibleTaps = 0.0;",
    "  vec2 tapUv = clamp(pageCoordinate.xy + vec2(-texelStep.x, -texelStep.y), pageBounds.xy, pageBounds.zw);",
    "  visibleTaps += step(mglTapReferenceDepth(pageCoordinate, tapUv, depthSlope, hasReceiverPlane, depthBias),",
    "    mglUnpackPageDepth(texture2D(uMglShadowAtlas, tapUv)));",
    "  tapUv = clamp(pageCoordinate.xy + vec2( texelStep.x, -texelStep.y), pageBounds.xy, pageBounds.zw);",
    "  visibleTaps += step(mglTapReferenceDepth(pageCoordinate, tapUv, depthSlope, hasReceiverPlane, depthBias),",
    "    mglUnpackPageDepth(texture2D(uMglShadowAtlas, tapUv)));",
    "  tapUv = clamp(pageCoordinate.xy + vec2(-texelStep.x,  texelStep.y), pageBounds.xy, pageBounds.zw);",
    "  visibleTaps += step(mglTapReferenceDepth(pageCoordinate, tapUv, depthSlope, hasReceiverPlane, depthBias),",
    "    mglUnpackPageDepth(texture2D(uMglShadowAtlas, tapUv)));",
    "  tapUv = clamp(pageCoordinate.xy + vec2( texelStep.x,  texelStep.y), pageBounds.xy, pageBounds.zw);",
    "  visibleTaps += step(mglTapReferenceDepth(pageCoordinate, tapUv, depthSlope, hasReceiverPlane, depthBias),",
    "    mglUnpackPageDepth(texture2D(uMglShadowAtlas, tapUv)));",
    "  return visibleTaps * 0.25;",
    "}",
    "",
    "// Legacy call site with no receiver normal: there is no plane to follow, so",
    "// the constant page bias stays in charge and the answer is the old one.",
    "float mglSampleVirtualShadowMapVisibility(",
    "  const in mat4 lightViewProjection,",
    "  const in vec4 pageScaleOffset,",
    "  const in vec4 pageBounds,",
    "  const in vec3 worldPosition,",
    "  const in float depthBias",
    ") {",
    "  return mglSampleVirtualShadowMapVisibility(",
    "    lightViewProjection, pageScaleOffset, pageBounds, worldPosition, depthBias, vec3(0.0));",
    "}",
    "",
    "// The three state answer ML-F17 needs. UNKNOWN means the atlas has NO data",
    "// for this sample, so the policy must still spend a world space ray on it.",
    "// Answering VISIBLE in that case is a light leak, not an optimisation.",
    "float mglVirtualShadowMapTraceState(",
    "  const in mat4 lightViewProjection,",
    "  const in vec4 pageScaleOffset,",
    "  const in vec4 pageBounds,",
    "  const in vec3 worldPosition,",
    "  const in float depthBias,",
    "  const in vec3 receiverWorldNormal,",
    "  out float visibility",
    ") {",
    "  visibility = 0.0;",
    "  vec3 pageCoordinate;",
    "  if (!mglProjectIntoShadowPage(lightViewProjection, pageScaleOffset, worldPosition, pageCoordinate)) {",
    "    return " + VSM_GLSL_STATE_CONSTANTS.unknown + ";",
    "  }",
    "  visibility = mglSampleVirtualShadowMapVisibility(",
    "    lightViewProjection, pageScaleOffset, pageBounds, worldPosition, depthBias, receiverWorldNormal);",
    "  return visibility >= 0.5 ? " + VSM_GLSL_STATE_CONSTANTS.visible + " : " + VSM_GLSL_STATE_CONSTANTS.occluded + ";",
    "}",
    "",
    "// Legacy call site with no receiver normal.",
    "float mglVirtualShadowMapTraceState(",
    "  const in mat4 lightViewProjection,",
    "  const in vec4 pageScaleOffset,",
    "  const in vec4 pageBounds,",
    "  const in vec3 worldPosition,",
    "  const in float depthBias,",
    "  out float visibility",
    ") {",
    "  return mglVirtualShadowMapTraceState(",
    "    lightViewProjection, pageScaleOffset, pageBounds, worldPosition, depthBias, vec3(0.0), visibility);",
    "}",
  ].join("\n");
}





export function describeVirtualShadowMapGlsl() {
  const source = buildVirtualShadowMapGlsl();
  return {
    characterCount: source.length,
    uniformNames: VSM_GLSL_UNIFORM_NAMES.slice(),
    functionNames: VSM_GLSL_FUNCTION_NAMES.slice(),
    samplerCount: 1,
    tapCount: 4,
    contactPreservingBias: true,
    usesScreenDerivatives: SHADOW_KERNEL_FORBIDDEN_TOKENS.some((token) => source.indexOf(token) >= 0),
  };
}
